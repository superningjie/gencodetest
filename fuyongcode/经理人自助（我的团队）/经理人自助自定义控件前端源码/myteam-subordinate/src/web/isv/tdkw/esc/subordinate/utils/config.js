export function getCardConfig(carddimensionIdCardStyleMap) {
  // 默认卡片尺寸
  let cardHeight = -Infinity;

  let cardModelMap = {};
  let cardModelHeightMap = {};

  if (!!carddimensionIdCardStyleMap) {
    for (const key in carddimensionIdCardStyleMap) {
      if (Object.hasOwnProperty.call(carddimensionIdCardStyleMap, key)) {
        const cardModelItem = carddimensionIdCardStyleMap[key];
        const [maxHeight, fields] = getCardModelMap(
          cardModelItem.cardStyleFields,
          cardModelItem
        );
        cardModelHeightMap[key] = maxHeight;
        cardModelMap[key] = fields;
        cardHeight = Math.max(cardHeight, cardModelHeightMap[key]);
      }
    }
    baseCardSize.h = cardHeight;
    getCardVModelMap(baseCardSize, cardModelMap);
  } else {
    cardModelMap = basicCardModel;
  }
  return { baseCardSize, cardModelHeightMap, cardModelMap };
}

// 得到卡片模板Map
function getCardModelMap(cardStyleFields, cardModelItem) {
  let cardHeight = -Infinity;

  const fields = [];

  if (cardModelItem.topbordercolor) {
    // 添加卡片顶部横条
    fields.push({
      tag: "rect",
      x: 0,
      y: 0,
      w: baseCardSize.w,
      h: 2,
      fill: () => cardModelItem.topbordercolor,
    });
  }

  // 添加上钻按钮
  fields.push(topNode);

  cardStyleFields.map((fieldItem) => {
    // 文字书写方向布局：start middle end
    const textAnchor =
      fieldItem.fontjustification === "1"
        ? "start"
        : fieldItem.fontjustification === "2"
        ? "middle"
        : "end";

    const x = parseInt(fieldItem.xcoordinate);
    const y = parseInt(fieldItem.ycoordinate);
    const w = parseInt(fieldItem.wide);
    const h = parseInt(fieldItem.high);

    const padding = 4;

    cardHeight = Math.max(cardHeight, h + y);

    // 字段名称包含‘avtor’:图片字段
    if (
      fieldItem.fieldidentifier &&
      fieldItem.fieldidentifier.indexOf("avtor") > -1
    ) {
      // 图片尺寸
      const size = Math.min(w, h) - padding * 2;

      fields.push({
        tag: "img",
        x: x + (w - size) / 2,
        y: y + (h - size) / 2,
        w: size,
        h: size,
        textAnchor,
        url: (data) => {
          const fieldVal = data.showFields
            ? data.showFields[fieldItem.fieldidentifier]
            : null;
          return fieldVal ? fieldVal : getDefaultHead(data.showFields);
        },
      });
    } else {
      fields.push({
        tag: "text",
        x: x + padding,
        y: y,
        w: w - padding * 2,
        h: h,
        fontSize: parseInt(fieldItem.wordsize),
        fontWeight: parseInt(fieldItem.bold) ? 600 : 100,
        color: "#212121",
        wMode: "lr",
        valign: "center",
        textAnchor,
        lineNums: 2,
        text: (data) => {
          let text = "";
          if (data.showFields) {
            text = data.showFields[fieldItem.fieldidentifier + ""];
            text = text === 0 ? "0" : text || "";
          }
          if (fieldItem.fieldidentifier === "establishmentdate") {
            text = text.substring(0, 10);
          }
          return [
            (fieldItem.beforecontent || "") +
              text +
              (fieldItem.aftercontent || ""),
          ];
        },
      });
    }
  });

  return [cardHeight, fields];
}

// 得到卡片纵向模板Map
function getCardVModelMap(baseCardSize, cardModelMap) {
  for (const key in cardModelMap) {
    if (Object.hasOwnProperty.call(cardModelMap, key)) {
      const card = cardModelMap[key];
      cardModelMap[key + "V"] = [];
      card.map((item, index) => {
        if (index === 0) {
          cardModelMap[key + "V"].push({
            tag: "rect",
            x: 0,
            y: 0,
            w: baseCardSize.h,
            h: 2,
            fill: () => "#5582F3",
          });
        } else {
          cardModelMap[key + "V"].push({
            ...item,
            x: item.y,
            y: item.x,
            w: item.h,
            h: item.w,
            wMode: "tb",
            valign: transValign(item.textAnchor),
            textAnchor: transTextAnchor(item.valign),
          });
        }
      });
    }
  }
}

// 转换样式
function transValign(textAnchor) {
  switch (textAnchor) {
    case "start":
      return "top";
    case "middle":
      return "center";
    case "end":
      return "bottom";
  }
}

// 转换样式
function transTextAnchor(valign) {
  switch (valign) {
    case "top":
      return "start";
    case "center":
      return "middle";
    case "bottom":
      return "end";
  }
}

